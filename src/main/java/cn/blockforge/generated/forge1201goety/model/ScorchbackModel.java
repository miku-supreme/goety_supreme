    public void renderOnly(PoseStack poseStack, VertexConsumer buffer, int packedLight,
            int packedOverlay, float red, float green, float blue, float alpha,
            java.util.Set<String> only) {
        renderBone("root", this.skeleton, poseStack, buffer, packedLight, packedOverlay,
                red, green, blue, alpha, only);
    }

    private void renderBone(String name, ModelPart part, PoseStack poseStack,
            VertexConsumer buffer, int packedLight, int packedOverlay,
            float red, float green, float blue, float alpha, java.util.Set<String> only) {
        if (part == null || !part.visible) {
            return;
        }
        poseStack.pushPose();
        part.translateAndRotate(poseStack);
        if (only == null || only.contains(name)) {
            float[] data = QUADS.get(name);
            if (data != null) {
                emit(data, poseStack.last(), buffer, packedLight, packedOverlay,
                        red, green, blue, alpha);
            }
        }
        String[] kids = CHILDREN.get(name);
        if (kids != null) {
            for (String kid : kids) {
                ModelPart sub = SafeModelParts.findOrNull(part, kid);
                if (sub != null) {
                    renderBone(kid, sub, poseStack, buffer, packedLight, packedOverlay,
                            red, green, blue, alpha, only);
                }
            }
        }
        poseStack.popPose();
    }

    private static void emit(float[] data, PoseStack.Pose pose, VertexConsumer buffer,
            int packedLight, int packedOverlay, float red, float green, float blue, float alpha) {
        Matrix4f matrix = pose.pose();
        Matrix3f normal = pose.normal();
        for (int i = 0; i < data.length; i += STRIDE) {
            float nx = data[i + 20];
            float ny = data[i + 21];
            float nz = data[i + 22];
            for (int v = 0; v < 4; v++) {
                buffer.vertex(matrix, data[i + v * 3], data[i + v * 3 + 1], data[i + v * 3 + 2])
                        .color(red, green, blue, alpha)
                        .uv(data[i + 12 + v * 2], data[i + 12 + v * 2 + 1])
                        .overlayCoords(packedOverlay)
                        .uv2(packedLight)
                        .normal(normal, nx, ny, nz)
                        .endVertex();
            }
        }
    }
